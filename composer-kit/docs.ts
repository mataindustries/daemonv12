/** Writes composer-kit/KIT.md from the kit's own data: node composer-kit/docs.ts */
import { writeFileSync } from 'node:fs';
import { getInstrument } from '../studio-001/rack/registry.ts';
import { pitchName } from '../studio-001/rack/curves.ts';
import { PATCHES } from './palette.ts';
import { GROOVES } from './grooves.ts';
import { FORMS } from './forms.ts';
import { MOVES } from './moves.ts';

const pair = (p: number | [number, number]) => (typeof p === 'number' ? `${p}` : `${p[0]}→${p[1]}`);
const instruments = [...new Set(PATCHES.filter(p => !p.internal).map(p => p.instrument))].map(id => getInstrument(id)!);
const md = `# DaemonV12 Composer Kit · catalogue

Generated by \`node composer-kit/docs.ts\`. Everything here runs on the unchanged Signature Rack (\`studio-001\`).

\`\`\`bash
node composer-kit/build.ts SPEC.json --check        # facts + taste check, writes nothing
node composer-kit/build.ts SPEC.json OUT_DIR        # OUT_DIR/score.json + OUT_DIR/<title>.mp3 (-16 LUFS)
node composer-kit/build.ts SPEC.json OUT_DIR --seed 9   # same spec, other seed: other fills and human timing
\`\`\`

Auditions: \`composer-kit/auditions/palette/<patch>.mp3\` (bar 1 cold, bar 2 hot) and \`composer-kit/auditions/grooves/<groove>.mp3\`.

## Spec

\`\`\`json
{
  "title": "Tin Saint",
  "world": "one sentence: what place is this, what is strange about it",
  "key": "D minor", "groove": "tresillo-clank", "seed": 41,
  "form": "machine-first",
  "hook": "lead",
  "voices": {
    "bass":    { "patch": "ratchet-servo" },
    "lead":    { "patch": "dead-marimba", "cell": { "bars": 2, "notes": [[0, 0.5, "D5", 0.9], [0.75, 0.25, "A4", 0.6]], "alt": [] } },
    "answer":  { "patch": "warm-throat" },
    "pad":     { "patch": "rosin-drone" },
    "texture": { "patch": "bearing-rain" }
  },
  "moves": [{ "move": "handOff", "section": "body", "to": "answer", "keep": true }]
}
\`\`\`

- **voices**: \`bass\` is required (\`{}\` uses the groove's own bass patch and line). \`lead\`, \`answer\`, \`pad\`, \`texture\` are the names the forms know; other names work in your own \`sections\`. Optional per voice: \`gainDb\`, \`pan\`. \`hat\` / \`perc\` may be given only to change their patch.
- **cell**: a loop of \`bars\` bars. A note is \`[beat, beats, pitch, velocity, options]\`; beat 0 is the start of the cell, a bar is 4 beats, pitch is a name like \`"Bb1"\`. \`alt\` (optional, same format) replaces the cell on every second pass: question, then answer. A voice with no cell is a drone (tonic + fifth); a \`bearing-rain\` voice with no cell is rain; a bass with no cell plays the groove's line.
- **hook**: the voice that owns the hook (default \`bass\`). Its cell IS the hook.
- **form**: a template below. Or write \`sections\` yourself: \`{ "id", "bars", "play": [...], "heat": 0.3 | { "bass": 0.8 }, "groove"?: "other-groove" }\`. If you write \`sections\`, no moves are applied unless you list them.
- **play tokens**: \`bass\`, \`drums\` (= \`kick\` + \`snare\`), \`hat\`, \`perc\`, any voice name; variants \`name:head\` (first half of its cell), \`name:tail\`, \`name:once\` (first pass only), \`name:last\` (final pass only), \`bass:groove\` (the groove's line instead of the bass cell).
- **heat** (0 cold … 1 hot) is where each patch sits on its own journey in that section. Same notes at heat 0.1 and 0.9 are two different bodies.
- **moves**: if given, they replace the form's default moves. One to three.
- Lines are moved by octaves into their instrument's range automatically; unknown articulations are dropped.

## Palette (${PATCHES.filter(p => !p.internal && p.character !== 'utility').length} patches + ${PATCHES.filter(p => !p.internal && p.character === 'utility').length} utility)

| Patch | Instrument | Character | Macro cold→hot | What it is, where it works |
|---|---|---|---|---|
${PATCHES.filter(p => !p.internal).map(p => `| \`${p.id}\` | ${p.instrument.replace('mechanical-orchestra/', '')} | ${p.character} | ${pair(p.macro)} | ${p.where} |`).join('\n')}

Ranges and note options (from the rack):

| Instrument | Range | Articulations | Per-note params |
|---|---|---|---|
${instruments.map(i => `| ${i.id.replace('mechanical-orchestra/', '')} | ${pitchName(i.range[0])}–${pitchName(i.range[1])} | ${Object.keys(i.articulations).join(', ')} | ${Object.keys(i.params).join(', ') || '—'}${i.family !== 'mechanical-orchestra' ? ', slide (beats)' : ''} |`).join('\n')}

Bass notes that matter: \`{"articulation":"accent","scoop":2}\` (hit hard, rise into it), \`"ghost"\` (dead note that sets up an accent), \`"staccato"\`, \`{"slide":0.1}\` (travel from the previous note), \`{"dive":5,"diveBeats":1}\` (bend out). Voice: \`"vowel"\`/\`"to"\` from mm oo oh aw ah uh eh ee, \`"articulation":"cry"\` or \`"fall"\`.

## Grooves (${GROOVES.length})

| Groove | BPM | Swing | Feel | Where it works | Bass patch |
|---|---|---|---|---|---|
${GROOVES.map(g => `| \`${g.id}\` | ${g.bpm} | ${g.swing} | ${g.feel} | ${g.where} | ${g.bassPatch} |`).join('\n')}

Kick maps (beats in a two-bar loop, 0–8), for writing a hook that locks to them or answers them:

${GROOVES.map(g => `- \`${g.id}\`: kick ${g.kick.map(h => h[0]).join(' ')} · snare ${g.snare.filter(h => h[2] !== 'ghost').map(h => h[0]).join(' ')}`).join('\n')}

## Forms (${FORMS.length})

| Form | Shape (bars) | When | Default moves |
|---|---|---|---|
${FORMS.map(f => `| \`${f.id}\` | ${f.shape} | ${f.when} | ${f.make('lead', () => true).moves.map(m => `${m.move}(${m.section})`).join(', ')} |`).join('\n')}

## Moves (${MOVES.length})

${MOVES.map(m => `### \`${m.id}\`\n${m.does}\n- **Works when:** ${m.works}\n- **Cheap when:** ${m.cheap}\n- Options: ${m.options}`).join('\n\n')}
`;
writeFileSync(new URL('./KIT.md', import.meta.url), md);
console.log('wrote composer-kit/KIT.md');
