// Write experiments/morph-05/MANIFEST.json: what was rendered, from which source, with which
// tools, and the SHA-256 of every source file and delivered artifact.
// Usage: node experiments/morph-05/manifest.mjs   (after build.mjs, checks.py and the DaemonV12 steps)
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url)), root = join(here, '..', '..');
const sha = p => createHash('sha256').update(readFileSync(p)).digest('hex');
const rel = p => relative(root, p);
const walk = d => readdirSync(d).flatMap(f => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
const sh = (cmd, args) => { try { return execFileSync(cmd, args, { encoding: 'utf8' }).split('\n')[0].trim(); } catch { return null; } };

const SOURCES = [
  ...['record.mjs', 'beast.mjs', 'v1.mjs', 'v2.mjs', 'v3.mjs', 'build.mjs', 'checks.py', 'manifest.mjs', 'daemonv12/export.mjs', 'daemonv12/nulltest.py'].map(f => join(here, f)),
  // reused read-only from earlier experiments
  ...['morph-03/cable.mjs', 'morph-03/dsp.mjs', 'morph-03/throat.mjs', 'morph-03/household.mjs', 'morph-03/analyze.py',
    'morph-04/kit.mjs', 'morph-04/perform.mjs', 'morph-04/events.mjs'].map(f => join(here, '..', f)),
];
const audio = join(here, 'audio');
const versions = {};
for (const v of ['v1', 'v2', 'v3']) {
  const d = join(audio, v), meta = JSON.parse(readFileSync(join(d, `cable-beast-${v}.meta.json`), 'utf8'));
  const files = walk(d).filter(p => !p.endsWith('.wav') || v === 'v3');
  versions[v] = {
    masterWav24Sha256: meta.wav24Sha256, masterWavCommitted: v === 'v3', frames: meta.frames,
    files: Object.fromEntries(files.map(p => [rel(p), sha(p)])),
  };
}
const d12 = join(here, 'daemonv12');
const d12manifest = JSON.parse(readFileSync(join(d12, 'results', 'cable-beast.daemonv12.render.json'), 'utf8'));
const nullTest = JSON.parse(readFileSync(join(d12, 'results', 'null-test.json'), 'utf8'));

const manifest = {
  title: 'CABLE//BEAST', experiment: 'MORPH//05', format: { sampleRate: 44100, channels: 2, masterBits: 24, bpm: 120, meter: '4/4', bars: 14, seconds: 28, frames: 1234800, fps: 60, pictureFrames: 1680 },
  baseCommit: '34e694f0c87a1bb3390ae868411a150f0d104f2f',
  tools: { node: process.version, ffmpeg: sh('ffmpeg', ['-version']), python: sh('python3', ['--version']), daemonv12: d12manifest.engine },
  reproduce: [
    'npm ci   # installs dev tools and builds dist/ (DaemonV12 CLI and timing functions)',
    'node experiments/morph-05/build.mjs v1 v2 && node experiments/morph-05/build.mjs v3 --stems',
    'pip install numpy scipy matplotlib && python3 experiments/morph-05/checks.py experiments/morph-05/audio/v3 experiments/morph-05/audio/v3/cable-beast-v3.checks.json --png experiments/morph-05/audio/spectrograms',
    'node experiments/morph-05/daemonv12/export.mjs experiments/morph-05/daemonv12/project',
    'node bin/daemonv12.js render experiments/morph-05/daemonv12/project/cable-beast.daemonv12.json --out-dir OUT --stems --format wav --json',
    'python3 experiments/morph-05/daemonv12/nulltest.py experiments/morph-05/daemonv12/project OUT experiments/morph-05/daemonv12/results/null-test.json',
  ],
  determinism: {
    external: 'v3 rendered twice into fresh directories on this runtime: master WAV and all 14 FLAC stems byte-identical; v1 and v2 re-rendered with identical master hashes',
    daemonv12: 'project rendered twice into fresh directories: master WAV and all 13 stems byte-identical',
  },
  sources: Object.fromEntries(SOURCES.map(p => [rel(p), sha(p)])),
  versions,
  daemonv12: {
    project: { file: rel(join(d12, 'project', 'cable-beast.daemonv12.json')), sha256: sha(join(d12, 'project', 'cable-beast.daemonv12.json')) },
    kits: Object.fromEntries(walk(join(d12, 'project', 'assets')).filter(p => !p.includes('/external/')).map(p => [rel(p), sha(p)])),
    externalStemsNotCommitted: 'assets/external/*.wav are regenerated by export.mjs (deterministic); their hashes are in results/cable-beast.daemonv12.render.json',
    renderWavSha256: d12manifest.wav.sha256, renderFrames: d12manifest.wav.frames,
    nullTest: { premaster: nullTest.premaster, triggers: nullTest.triggers },
  },
};
writeFileSync(join(here, 'MANIFEST.json'), JSON.stringify(manifest, null, 1) + '\n');
console.log(`MANIFEST.json: ${Object.keys(manifest.sources).length} sources, ${Object.values(versions).reduce((a, v) => a + Object.keys(v.files).length, 0)} version files, ${Object.keys(manifest.daemonv12.kits).length} kit files`);
if (!existsSync(join(audio, 'v3', 'stems', 'stems.json'))) console.warn('v3 stems missing');
