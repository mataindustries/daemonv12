#!/usr/bin/env python3
"""Make a stem-based DaemonV12 session from the original Python score renders.

The session is an interchange/editing view of the five aligned stems, not the
note-level score; compose.py is the authoritative composition and mix source.
FFmpeg is used solely for the engine's required 44.1 kHz signed-16 WAV format.
"""

import json
import math
from pathlib import Path
import subprocess
import wave


ROOT = Path(__file__).resolve().parent
STEMS = ("drums", "bass", "hook", "harmony", "texture")
BPM = 116


def main():
    assets = ROOT / "assets" / "stems"
    assets.mkdir(parents=True, exist_ok=True)
    frame_count = None
    tracks = []
    for name in STEMS:
        source = ROOT / "stems" / f"{name}.wav"
        if not source.is_file():
            raise SystemExit(f"Missing source stem: {source}. Render the score first.")
        target = assets / f"{name}.wav"
        subprocess.run(
            ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", str(source),
             "-ar", "44100", "-ac", "2", "-c:a", "pcm_s16le", str(target)],
            check=True,
        )
        with wave.open(str(target), "rb") as wav:
            if (wav.getframerate(), wav.getnchannels(), wav.getsampwidth()) != (44100, 2, 2):
                raise ValueError(f"Unexpected WAV format: {target}")
            frames = wav.getnframes()
        if frame_count is None:
            frame_count = frames
        elif frames != frame_count:
            raise ValueError("Stems must have the same duration and start at frame zero")
        tracks.append({
            "id": name,
            "instrument": {"type": "sampler", "sample": f"assets/stems/{name}.wav"},
            "clips": [{"bar": 1, "pattern": "full-stem"}],
            "patterns": [{"id": "full-stem", "bars": 1,
                          "notes": [{"start": "1:1", "velocity": 1}]}],
        })
    seconds = frame_count / 44100
    bars = max(1, math.ceil(seconds * BPM / 240))
    project = {
        "formatVersion": 1,
        "title": "EXIT VELOCITY // 2099 V3 — stem session",
        "description": "Original Python-composed stems, aligned at zero. The score and final master are generated by the accompanying Python scripts.",
        "bpm": BPM,
        "timeSignature": "4/4",
        "bars": bars,
        "render": {"duration": {"seconds": round(seconds, 6)}, "tail": "auto"},
        "master": {"gainDb": -2},
        "tracks": tracks,
    }
    output = ROOT / "daemon-session.json"
    output.write_text(json.dumps(project, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {output.name}: {len(tracks)} aligned stems, {seconds:.6f} s")


if __name__ == "__main__":
    main()
