// Event maps: every scheduled event of an arrangement, with its exact time, grid position and
// musical meaning. Built from the same arrays the renders read, so the map cannot drift.
import { at, noteName } from './perform.mjs';

/** "bar.beat.16th" (1-based); 32nd notes show as e.g. 2.4.3½. */
export function position(step) {
  const bar = Math.floor(step / 16) + 1, beat = Math.floor((step % 16) / 4) + 1, six = (step % 4) + 1;
  const whole = Math.floor(six), half = six - whole >= 0.5 ? '½' : '';
  return `${bar}.${beat}.${whole}${half}`;
}

export function row(step, part, event, extra = {}) {
  return { step, time: +at(step).toFixed(4), position: position(step), part, event, ...extra };
}

/** Bass notes as event rows. */
export function noteRows(notes) {
  return notes.map(n => {
    const detail = [];
    if (n.pop) detail.push(n.pop === 2 ? 'flageolet octave pop' : 'flageolet twelfth pop');
    if (n.bendTo) detail.push(`bend to ${noteName(n.bendTo)}`);
    if (n.snapTo) detail.push(`re-tension to ${noteName(n.snapTo)} at ${position(n.snapAt)}`);
    if (n.vowel) detail.push(`"${n.vowel}" vowel`);
    if (n.stretch) detail.push(`strike stretch ${n.stretch}`);
    return row(n.step, 'cable bass', n.kind, { pitch: noteName(n.midi), lengthSteps: n.len, velocity: n.amp ?? (n.kind === 'ghost' ? 0.6 : 1), detail: detail.join('; ') });
  });
}

export function eventMapMarkdown(name, rows, summary = '') {
  const sorted = [...rows].sort((a, b) => a.step - b.step || a.part.localeCompare(b.part));
  const lines = [
    `# ${name}: event map`, '',
    'Generated by `build.mjs` from the arrangement source. Times are seconds from the loop start (120 BPM,',
    '16th = 0.125 s); positions are bar.beat.16th. Velocities are linear gains before mixing.', '',
    ...(summary ? [summary, ''] : []),
    '| Time (s) | Position | Step | Part | Event | Pitch | Velocity | Detail |',
    '|---:|---|---:|---|---|---|---:|---|',
    ...sorted.map(r => `| ${r.time.toFixed(3)} | ${r.position} | ${r.step} | ${r.part} | ${r.event} | ${r.pitch ?? ''} | ${r.velocity ?? ''} | ${r.detail ?? ''} |`),
  ];
  return lines.join('\n') + '\n';
}
