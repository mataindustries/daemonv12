/**
 * Write experiments/cathedral-experiment-001/INSTRUMENTS.md (and, with --json FILE, the registry entries as JSON) from the
 * instrument definitions themselves, so the documented controls cannot drift from the code.
 *
 *   node experiments/cathedral-experiment-001/instruments/docs.ts [--json OUT.json]
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATHEDRAL_INSTRUMENTS } from './registry.ts';
import { LAB_VERSION } from './common.ts';
import type { ControlSpec } from '../../../studio-001/rack/types.ts';

const HERE = dirname(fileURLToPath(import.meta.url));
const NAMES = ['C', 'C♯', 'D', 'E♭', 'E', 'F', 'F♯', 'G', 'A♭', 'A', 'B♭', 'B'];
const note = (m: number) => `${NAMES[m % 12]}${Math.floor(m / 12) - 1}`;
const range = (c: ControlSpec) => (c.name === 'output' ? 'text' : `${c.min} … ${c.max}`);
const FAMILY_INTRO: Record<string, string> = {
  'throne-volt': 'An analog-style lead and polysynth. One instrument; any number of voices (chords are separate voices, a legato note continues the voice nearest in pitch).',
  'cathedral-engine': 'A synthetic pipe organ in three divisions. Write one part per division; notes are written at 8\' pitch (a 16\' rank sounds an octave lower, a 4\' an octave higher). Every rank is a continuous control (a drawstop that can move mid-phrase); the macro is a crescendo pedal.',
  'heaven-mass': 'A synthetic choir in four sections. Write one part per section (or more, for divisi); each part is an ensemble of individually different singers. Vowels are per note (`vowel`, `to`); the macro grows the ensemble from intimate to heavenly.',
};

export function instrumentsMarkdown(): string {
  const out: string[] = [
    '# Cathedral Experiment · instrument reference',
    '',
    `Generated by \`node experiments/cathedral-experiment-001/instruments/docs.ts\` (lab ${LAB_VERSION}). Do not edit by hand.`,
    '',
    'Three new instrument families for the Signature Rack: THRONE//VOLT, CATHEDRAL//ENGINE and HEAVEN//MASS. They implement the rack\'s instrument interface and its calibration (a reference note at macro 0, velocity 0.8 renders at -20 dBFS RMS, so part gains compare across families), are deterministic (seeded) and use no recordings, samples, presets or impulse responses. **Not approved and not frozen**; licensing pending.',
    '',
    '## Using them',
    '',
    'They are registered per process, like the Timbre Lab, by loading the opt-in hook before the rack (the rack, its registry and the frozen engines are not edited):',
    '',
    '```bash',
    'node --import ./experiments/cathedral-experiment-001/instruments/register.ts studio-001/rack/cli.ts list',
    'node --import ./experiments/cathedral-experiment-001/instruments/register.ts studio-001/rack/cli.ts render SCORE.json NEW_DIR',
    'node --import ./experiments/cathedral-experiment-001/instruments/register.ts studio-001/rack/cli.ts kit throne-volt NEW_DIR --pitches 60-72 --macro 0.6',
    '```',
    '',
    'In a score they are ordinary parts, for example `{ "id": "lead", "instrument": "throne-volt", "macro": 0.6, "notes": [[0, 2, "Ab4", 0.9, { "articulation": "accent" }], [2, 2, "F4", 0.85, { "articulation": "legato", "slide": 0.3, "fall": 3 }]] }`. Controls accept a constant, `[[beat, value], ...]` ramps or `{ "steps": [[beat, value], ...], "glide": beats }`, either absolute (`controls`) or added to the macro mapping (`offsets`), and are clamped to the listed range. `expression` (0..1, 0.7 neutral) scales velocity as in the rack. The registry the hook installs lists the frozen rack instruments first, then the Timbre Lab, then these.',
    '',
  ];
  let family = '';
  for (const i of CATHEDRAL_INSTRUMENTS) {
    if (i.family !== family) {
      family = i.family;
      out.push(`## ${i.macro.label} · ${family}`, '', FAMILY_INTRO[family] ?? '', '');
    }
    out.push(`### \`${i.id}\` · ${i.name}`, '', i.description, '',
      `Version \`${i.version}\` · range ${note(i.range[0])}–${note(i.range[1])} (MIDI ${i.range[0]}–${i.range[1]}) · suggested gain ${i.suggestedGainDb} dB · macro \`${i.macro.label}\``, '',
      '| Articulation | Effect |', '|---|---|', ...Object.entries(i.articulations).map(([k, v]) => `| \`${k}\` | ${v} |`), '',
      '| Control | Range | What it does |', '|---|---|---|', ...i.controls.map(c => `| \`${c.name}\` | ${range(c)} | ${c.description} |`), '',
      `Setup (per part): ${i.setup.map(c => `\`${c.name}\` (${range(c)}: ${c.description})`).join('; ')}.`, '',
      `Per-note parameters: ${Object.entries(i.params).map(([k, v]) => `\`${k}\` (${v})`).join('; ') || 'none'}.`, '');
  }
  return out.join('\n');
}

export function instrumentsJson() {
  return {
    schema: 'daemonv12.signature-rack.registry/1', lab: `cathedral-experiment ${LAB_VERSION}`,
    instruments: CATHEDRAL_INSTRUMENTS.map(({ render: _render, ...info }) => info),
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(HERE, '..', 'INSTRUMENTS.md'), instrumentsMarkdown() + '\n');
  const j = process.argv.indexOf('--json');
  if (j > 0 && process.argv[j + 1]) writeFileSync(process.argv[j + 1]!, JSON.stringify(instrumentsJson(), null, 1) + '\n');
  console.log(`wrote INSTRUMENTS.md (${CATHEDRAL_INSTRUMENTS.length} instruments)`);
}
